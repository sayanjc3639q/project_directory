/**
 * @file scripts/generate-codemap.mjs
 * @purpose Generate docs/CODEMAP.md by inspecting source file headers and imports.
 * @tags script, codemap, documentation, generator
 */
import fs from "node:fs";
import path from "node:path";

const SRC_DIRS = ["src", "scripts"];
const EXCLUDE_EXT = [".test.ts", ".test.tsx"];
const INCLUDE_EXT = [".ts", ".tsx", ".mjs", ".js"];

function findFiles(dir) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const list = fs.readdirSync(dir, { withFileTypes: true });
  for (const item of list) {
    const full = path.join(dir, item.name);
    if (item.isDirectory()) {
      results = results.concat(findFiles(full));
    } else {
      const matchExt = INCLUDE_EXT.some((ext) => item.name.endsWith(ext));
      const notExcluded = !EXCLUDE_EXT.some((ext) => item.name.endsWith(ext));
      if (matchExt && notExcluded) {
        results.push(full);
      }
    }
  }
  return results;
}

function parseHeader(content) {
  const fileMatch = content.match(/@file\s+([^\r\n*]+)/);
  const purposeMatch = content.match(/@purpose\s+([^\r\n*]+)/);
  const tagsMatch = content.match(/@tags\s+([^\r\n*]+)/);
  return {
    file: fileMatch ? fileMatch[1].trim() : "",
    purpose: purposeMatch ? purposeMatch[1].trim() : "",
    tags: tagsMatch ? tagsMatch[1].trim() : ""
  };
}

function parseImports(content) {
  const matches = [...content.matchAll(/from\s+["'](@\/[^"']+|\.\/[^"']+|\.\.\/[^"']+)["']/g)];
  return matches.map((m) => m[1]);
}

function parseExports(content) {
  const exports = [];
  const exportMatches = [...content.matchAll(/export\s+(?:const|function|class|type|interface|default)\s+([A-Za-z0-9_]+)/g)];
  for (const m of exportMatches) {
    exports.push(m[1]);
  }
  return exports;
}

function run() {
  const allFiles = SRC_DIRS.flatMap(findFiles);
  const fileData = [];

  for (const f of allFiles) {
    const rel = path.relative(process.cwd(), f).replace(/\\/g, "/");
    const content = fs.readFileSync(f, "utf-8");
    const lines = content.split(/\r?\n/).length;
    const meta = parseHeader(content);
    const imports = parseImports(content);
    const exports = parseExports(content);
    fileData.push({ rel, lines, meta, imports, exports });
  }

  const importedBy = {};
  for (const file of fileData) {
    for (const imp of file.imports) {
      if (!importedBy[imp]) importedBy[imp] = [];
      importedBy[imp].push(file.rel);
    }
  }

  const warnings = fileData.filter((f) => f.lines > 120);

  let md = "# CODEMAP\\n\\n";
  md += "> GENERATED by scripts/generate-codemap.mjs. Do not edit directly.\\n\\n";
  md += "## File Index\\n\\n";
  md += "| Path | Lines | Purpose | Tags | Exports | Local Imports |\\n";
  md += "| :--- | :--- | :--- | :--- | :--- | :--- |\\n";

  for (const f of fileData) {
    const expStr = f.exports.slice(0, 4).join(", ");
    const impStr = f.imports.slice(0, 3).join(", ");
    md += `| \`${f.rel}\` | ${f.lines} | ${f.meta.purpose || "N/A"} | ${f.meta.tags || "N/A"} | ${expStr || "-"} | ${impStr || "-"} |\\n`;
  }

  md += "\\n## Warnings (> 120 lines)\\n\\n";
  if (warnings.length === 0) {
    md += "No files exceed 120 lines.\\n";
  } else {
    for (const w of warnings) {
      md += `- \`${w.rel}\` (${w.lines} lines)\\n`;
    }
  }

  fs.mkdirSync(path.join(process.cwd(), "docs"), { recursive: true });
  fs.writeFileSync(path.join(process.cwd(), "docs", "CODEMAP.md"), md);
  console.log("CODEMAP.md generated successfully.");
}

run();
